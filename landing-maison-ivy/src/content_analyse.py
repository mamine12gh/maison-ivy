"""Contenu de l'analyse : 3 options par composant, notées sur 5 critères pondérés.
Critères (poids) : Conversion 35 · Confiance 20 · Angle 15 · Clarté 15 · Faisabilité & risque 15.
Scores de 1 à 5, dans cet ordre."""

CRITERIA = [
    ("Conversion", 35, "Effet attendu sur le taux d'ajout au panier et de commande."),
    ("Confiance", 20, "Crédibilité, honnêteté, absence de risque de retour ou de plainte."),
    ("Angle", 15, "Fidélité à « S'il peut le dire, ça l'imprime » et à la pub (même message)."),
    ("Clarté", 15, "Effort cognitif : compris en 3 secondes, facile à survoler sur mobile."),
    ("Faisabilité", 15, "Coût, délai, vitesse de page, conformité (UE, Meta, marques)."),
]

def total(s):
    return round(sum(w * v for (_, w, _), v in zip(CRITERIA, s)) / 5)

